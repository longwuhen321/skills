# ==================== md2zh 配置 ====================
md2zh_config = {
    # Python 解释器的完整路径（必需项）。AI 助手使用此路径执行
    # scripts/md2zh_pipeline.py，pipeline 也会校验运行解释器与此一致
    # （"全程同一个 Python"）。缺失/失效时 pipeline 拒绝执行并提示
    # 重跑 /md2zh 配置向导。
    "python_path": "/path/to/your/python",

    # 模糊内容（ambiguous_region）由谁决定：user = 展示给用户收集决策；
    # ai = 由 AI 助手依据上下文决定。由 /md2zh 配置向导写入，
    # pipeline 的 configure 子命令维护，无需手动编辑。
    "ambiguous_content_decider": "user",

    # 翻译输出目录（选填）：留空 "" = 输出在源文件同级目录（默认）；
    # 指定路径 = 翻译文件输出到该目录（目录不存在自动创建），并把源文件旁的
    # <stem>.assets 图片文件夹一并复制过去（md 内图片引用不变，正常显示）。
    "output_dir": "",

    # 是否开启树形翻译流程（选填，默认 true）：true = 指定目录且树内可翻译
    # .md ≥ 2 个时按树形流程镜像输出；false = 目录不再自动触发树形，遇到
    # 多个可翻译 .md 时停下询问用户指定单个文件。
    "tree_translation": True,

    # 翻译块软目标（选填，默认 16000 字符，建议 10000–24000）：单块可译内容
    # （等待翻译的字符，不含代码/公式/链接目标等保护内容）的目标值。
    # 以标题区间为天然边界；超出目标时只在可译 unit 边界拆分，不在 unit
    # 内硬切，因此单个不可分 unit 可能超过该目标。
    "max_block_chars": 16000,
}
